def test_mentions_and_lookup(tmp_path: Path) -> None:
    _install(tmp_path)
    cat = tk.discover(tmp_path)
    names = [p.command for p in tk.mentioned_parts(cat, "Let's run /recon update deal, then use the reviewer agent; the guard hook fired; /gate main")]
    assert names == ["/recon [topic]", "reviewer", "/gate", "guard"]
    assert tk.mentioned_parts(cat, "a reconnaissance of the reviewers' notes") == []     # bare words are not mentions
    assert tk.mentioned_parts(cat, "") == [] and tk.mentioned_parts(tk.ToolkitCatalog(), "/recon") == []
    text = tk.lookup(cat, "run /recon on it", max_chars=400)
    assert text.startswith("### /recon [topic] (skill)\n# Recon: $ARGUMENTS") and len(text) <= 400
    assert tk.lookup(cat, "nothing here") == ""
    both = tk.lookup(cat, "/recon then the reviewer agent", max_chars=5000)
    assert "### reviewer (agent)" in both and both.index("### /recon") < both.index("### reviewer")


def test_watcher_rescans_on_its_cadence_and_reports_installs(tmp_path: Path) -> None:
    clock = {"t": 1000.0}
    watcher = tk.ToolkitWatcher(lambda: str(tmp_path), rescan_s=lambda: 30.0, clock=lambda: clock["t"])
    assert watcher.refresh() is False and watcher.catalog.is_empty           # nothing there yet
    _install(tmp_path, agents=False, rules=False, extras=False)
    assert watcher.refresh() is False                                        # too soon
    clock["t"] += 31
    assert watcher.refresh() is True and watcher.catalog.summary() == "2 skills"
    clock["t"] += 31
    assert watcher.refresh() is False                                        # unchanged
    (tmp_path / ".claude" / "skills" / "recon" / "SKILL.md").write_text(_SKILL + "\nmore\n", encoding="utf-8")
    assert watcher.refresh(force=True) is True                               # an edit changes the signature
    other = tmp_path / "other"
    other.mkdir()
    moved = tk.ToolkitWatcher(lambda: str(other), rescan_s=lambda: 30.0, clock=lambda: clock["t"])
    moved.refresh(force=True)
    assert moved.catalog.is_empty and moved.catalog.root == str(other)


