def test_render_catalog_fits_its_budget_and_sheds_detail_in_order(tmp_path: Path) -> None:
    _install(tmp_path)
    cat = tk.discover(tmp_path)
    full = tk.render_catalog(cat, max_chars=3000)
    assert full.startswith("Installed in the user's repository")
    for line_start in ("Skills: /pr-brief [base-branch] (user-invoked):", "Agents: reviewer (opus; read-only):",
                       "Workflows: /gate:", "Rules: tk-python (**/*.py, **/pyproject.toml)", "Hooks: guard:",
                       "Repo commands (CLAUDE.local.md): test: `.venv/Scripts/python -m pytest`",
                       "Working loop (house rules): Unfamiliar code"):
        assert any(line.startswith(line_start) for line in full.splitlines()), line_start
    skills_line = next(line for line in full.splitlines() if line.startswith("Skills: "))
    assert "; /recon [topic]: Use at the start of work" in skills_line
    assert len(full) <= 3000
    smaller = tk.render_catalog(cat, max_chars=len(full) - 40)
    assert len(smaller) <= len(full) - 40 and "/recon [topic]" in smaller
    tiny = tk.render_catalog(cat, max_chars=420)
    assert len(tiny) <= 420 and "Rules:" not in tiny and "Hooks:" not in tiny


