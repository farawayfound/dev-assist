def test_the_clone_enriches_installed_parts_only(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    clone = tmp_path / "claude-toolkit"
    _install(repo, agents=False, rules=False, extras=False)
    (clone / "modules").mkdir(parents=True)
    (clone / "modules" / "index.json").write_text(json.dumps({
        "recon": {"kind": "skill", "what": "/recon [topic]: read-only reconnaissance by four agents in one message, condensed into a 25-line brief."},
        "scope": {"kind": "skill", "what": "/scope: not installed here"},
    }), encoding="utf-8")
    assert tk.find_toolkit_dir(str(clone)) == clone and tk.find_toolkit_dir("", home=tmp_path) == clone
    assert tk.find_toolkit_dir(str(tmp_path / "nope"), home=tmp_path / "empty") is None
    cat = tk.discover(repo, toolkit_dir=str(clone))
    recon = cat.find("recon")
    assert recon.description == "read-only reconnaissance by four agents in one message, condensed into a 25-line brief."
    assert cat.find("scope") is None and "/pr-brief" in cat.find("pr-brief").command
    assert "Drafts the PR title" in cat.find("pr-brief").description            # not in the clone's index: its own text
    plain = tk.discover(repo, home=tmp_path / "empty")
    assert "read-only reconnaissance by four parallel agents" in plain.find("recon").description


@pytest.mark.skipif(not (REAL_TOOLKIT / "modules" / "index.json").is_file(), reason="the claude-toolkit clone is not on this machine")
def test_the_real_toolkit_files_parse(tmp_path: Path) -> None:
    """Every real SKILL.md / agent file has a name and a description, and the live set's house
    rules give a working loop -- so the catalog an actual install produces is never empty. The
    toolkit is edited independently of this repo, so this asserts its shape, never its contents."""
    claude = tmp_path / ".claude"
    import shutil

    shutil.copytree(REAL_TOOLKIT / "modules" / "skills", claude / "skills")
    (claude / "agents").mkdir()
    for f in (REAL_TOOLKIT / "modules" / "agents").glob("*.md"):
        if f.name != "README.md":
            shutil.copy(f, claude / "agents" / f.name)
    house = (REAL_TOOLKIT / "modules" / "house-rules" / "CLAUDE.md").read_text(encoding="utf-8")
    (tmp_path / "CLAUDE.local.md").write_text(f"<!-- dev-toolkit:begin -->\n{house}\n<!-- dev-toolkit:end -->\n", encoding="utf-8")
    cat = tk.discover(tmp_path, toolkit_dir=str(REAL_TOOLKIT))
    skills, agents = cat.by_kind("skill"), cat.by_kind("agent")
    assert skills and agents
    assert all(p.name and p.description for p in skills + agents)
    assert cat.loop and cat.loop[0].strip()
    assert len(tk.render_catalog(cat, 3000)) <= 3000
    first = skills[0]
    assert f"/{first.name}" in tk.lookup(cat, f"use /{first.name} first", 2000)
