def _install(root: Path, *, skills: bool = True, agents: bool = True, rules: bool = True, extras: bool = True) -> None:
    claude = root / ".claude"
    if skills:
        (claude / "skills" / "recon").mkdir(parents=True)
        (claude / "skills" / "recon" / "SKILL.md").write_text(_SKILL, encoding="utf-8")
        (claude / "skills" / "pr-brief").mkdir(parents=True)
        (claude / "skills" / "pr-brief" / "SKILL.md").write_text(_SKILL_USER_ONLY, encoding="utf-8")
    if agents:
        (claude / "agents").mkdir(parents=True, exist_ok=True)
        (claude / "agents" / "reviewer.md").write_text(_AGENT, encoding="utf-8")
    if rules:
        (claude / "rules").mkdir(parents=True, exist_ok=True)
        (claude / "rules" / "tk-python.md").write_text(_RULE, encoding="utf-8")
    if extras:
        (claude / "workflows").mkdir(parents=True, exist_ok=True)
        (claude / "workflows" / "gate.js").write_text(
            "export const meta = { name: 'gate', description: 'Eight review passes in parallel.' }\n", encoding="utf-8")
        (claude / "hooks" / "tk").mkdir(parents=True, exist_ok=True)
        (claude / "hooks" / "tk" / "guard.mjs").write_text(
            "// guard.mjs: PreToolUse hook that denies destructive commands.\nexport {};\n", encoding="utf-8")
        (claude / "settings.local.json").write_text(json.dumps({"hooks": {"PreToolUse": [], "UserPromptSubmit": []}}),
                                                     encoding="utf-8")
        (root / "CLAUDE.local.md").write_text(_HOUSE, encoding="utf-8")
        (root / ".git").mkdir(exist_ok=True)
        (root / ".git" / "dev-toolkit.json").write_text(json.dumps({
            "version": 2, "files": {"skills/recon/SKILL.md": {"part": "recon", "sha256": "x", "created": True},
                                    "agents/reviewer.md": {"part": "reviewer", "sha256": "y", "created": True}},
        }), encoding="utf-8")


def test_parse_frontmatter_handles_quotes_lists_and_booleans() -> None:
    meta, body = tk.parse_frontmatter(_SKILL_USER_ONLY)
    assert meta == {"name": "pr-brief", "description": "Drafts the PR title and body from the diff.",
                    "disable-model-invocation": True, "argument-hint": "[base-branch]"}
    assert body.startswith("# PR brief")
    meta, _ = tk.parse_frontmatter(_RULE)
    assert meta["paths"] == ["**/*.py", "**/pyproject.toml"]
    meta, _ = tk.parse_frontmatter("---\ntools: [Read, 'Grep', \"Bash\"]\n# comment\nempty:\n---\nbody")
    assert meta == {"tools": ["Read", "Grep", "Bash"], "empty": []}
    assert tk.parse_frontmatter("no frontmatter\n---\nx") == ({}, "no frontmatter\n---\nx")
    assert tk.parse_frontmatter("\ufeff---\nname: bom\n---\nb")[0] == {"name": "bom"}


def test_discover_reads_the_whole_install(tmp_path: Path) -> None:
    _install(tmp_path)
    cat = tk.discover(tmp_path)
    assert not cat.is_empty and cat.root == str(tmp_path)
    assert cat.summary() == "2 skills, 1 agent, 1 workflow, 1 rule, 1 hook"
    recon = cat.find("recon")
    assert recon is not None and recon.kind == "skill" and recon.command == "/recon [topic]"
    assert "read-only reconnaissance" in recon.description and "Read-only: no edits" in recon.body
    assert cat.find("/pr-brief").user_invoked_only and cat.find("pr-brief", "agent") is None
    reviewer = cat.find("reviewer")
    assert reviewer.kind == "agent" and reviewer.model == "opus" and reviewer.tools == "Read, Grep, Glob, Bash"
    rule = cat.find("tk-python")
    assert rule.kind == "rule" and rule.paths == ("**/*.py", "**/pyproject.toml") and rule.description == "Python guidance"
    gate = cat.find("gate")
    assert gate.kind == "workflow" and gate.command == "/gate" and gate.description == "Eight review passes in parallel."
    guard = cat.find("guard")
    assert guard.kind == "hook" and "denies destructive commands" in guard.description
    assert cat.loop[0].startswith("Unfamiliar code: /recon") and len(cat.loop) == 3
    assert cat.commands == (("test", ".venv/Scripts/python -m pytest"), ("lint", ".venv/Scripts/python -m ruff check ."))
    assert cat.facts == ("Stack: python; package manager: pip.", "No CI workflow found: treat every command above as unverified.")
    assert cat.hooks_registered == ("PreToolUse", "UserPromptSubmit") and cat.manifest_parts == ("recon", "reviewer")
    assert cat.signature and all(len(entry) == 3 for entry in cat.signature)


